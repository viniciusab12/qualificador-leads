-- Estrutura do banco do Termo no Supabase (PostgreSQL).
--
-- Este arquivo documenta como a tabela de leads está configurada e serve para
-- recriar o banco num projeto novo: cole no SQL Editor do Supabase e rode.
-- Num projeto que já tem a tabela, rode da parte 2 em diante (tudo pode ser repetido sem problema).
--
-- Como a segurança funciona:
-- - O app acessa a tabela só pelo servidor, com a chave service_role.
-- - A service_role ignora o RLS. Quem separa as contas é o filtro por dono_email
--   em src/supabase_db.py, conferido em tests/test_supabase_db.py.
-- - O RLS fica ligado e sem políticas para anon e authenticated. Assim, a chave
--   pública (que é pública por natureza) não consegue ler nem alterar nenhum lead.


-- 1. Tabela ------------------------------------------------------------------

create table if not exists public.leads (
    id               bigint generated by default as identity primary key,
    dono_email       text        not null,  -- e-mail (Google, e-mail e senha) ou "github|<id>"
    empresa          text        not null,
    contato          text        not null,
    segmento         text        not null,
    necessidade      text        not null,
    descricao        text,
    orcamento        numeric     not null,
    prazo            text        not null,
    contato_decisor  boolean     not null,
    nota             integer,
    classificacao    text,
    justificativa    text,
    analise_ia       text,
    status           text        not null default 'Novo',
    criado_em        timestamptz not null default now()
);

-- Colunas das etapas 7 e 8 (regras por conta e acompanhamento).
-- "add column if not exists" não mexe nas colunas que já existem.
alter table public.leads add column if not exists criterios_versao integer not null default 0;
alter table public.leads add column if not exists anotacoes        jsonb   not null default '[]'::jsonb;
alter table public.leads add column if not exists proximo_contato  date;

-- Regras de pontuação de cada conta. Cada alteração vira uma linha nova
-- (versão 1, 2, 3...), então as versões antigas ficam guardadas.
create table if not exists public.criterios_conta (
    id          bigint generated by default as identity primary key,
    dono_email  text        not null,
    versao      integer     not null,
    config      jsonb       not null,
    criado_em   timestamptz not null default now(),
    unique (dono_email, versao)
);


-- 2. Índice: toda consulta do app filtra por dono_email --------------------------

create index if not exists leads_dono_email_idx on public.leads (dono_email);
-- criterios_conta já tem índice por causa do unique (dono_email, versao)


-- 3. RLS ligado, sem políticas: a chave pública não acessa nada ------------------

alter table public.leads enable row level security;
alter table public.criterios_conta enable row level security;


-- 4. Permissões: só a service_role (usada pelo servidor do app) ------------------

revoke all on table public.leads from anon, authenticated;
revoke all on table public.criterios_conta from anon, authenticated;
grant select, insert, update, delete on table public.leads to service_role;
grant select, insert, update, delete on table public.criterios_conta to service_role;
grant usage, select on all sequences in schema public to service_role;


-- 5. Conferência (rode depois e confira os resultados) --------------------------
-- Rode cada consulta separadamente: o SQL Editor mostra só o resultado da última.

-- 5a. Deve mostrar só linhas com grantee = service_role (e postgres, o dono).
--     Se aparecer anon ou authenticated, rode a parte 4 de novo.
select grantee, privilege_type
from information_schema.role_table_grants
where table_schema = 'public' and table_name in ('leads', 'criterios_conta')
order by table_name, grantee, privilege_type;

-- 5b. Deve mostrar rls_ligado = true.
select relname as tabela, relrowsecurity as rls_ligado
from pg_class
where oid in ('public.leads'::regclass, 'public.criterios_conta'::regclass);

-- 5c. Não deve mostrar nenhuma linha (nenhuma política abre a tabela).
select policyname, roles, cmd
from pg_policies
where schemaname = 'public' and tablename in ('leads', 'criterios_conta');
